package main

import (
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// QuickKnowledgeBuilder builds knowledge base quickly
type QuickKnowledgeBuilder struct {
	sourceDir string
	targetDir string
	startTime time.Time
}

// NewQuickKnowledgeBuilder creates new builder
func NewQuickKnowledgeBuilder(sourceDir, targetDir string) *QuickKnowledgeBuilder {
	return &QuickKnowledgeBuilder{
		sourceDir: sourceDir,
		targetDir: targetDir,
		startTime: time.Now(),
	}
}

// Build builds knowledge base
func (qkb *QuickKnowledgeBuilder) Build() error {
	log.Println("=== 🚀 QUICK KNOWLEDGE BASE BUILD ===")

	// Create directories
	if err := qkb.createDirs(); err != nil {
		return fmt.Errorf("create dirs: %w", err)
	}

	// Copy important files
	if err := qkb.copyImportantFiles(); err != nil {
		return fmt.Errorf("copy files: %w", err)
	}

	// Create index
	if err := qkb.createIndex(); err != nil {
		return fmt.Errorf("create index: %w", err)
	}

	// Summary
	qkb.printSummary()

	return nil
}

// createDirs creates directories
func (qkb *QuickKnowledgeBuilder) createDirs() error {
	dirs := []string{
		"content/skills",
		"content/agents",
		"content/rules",
		"content/workflows",
		"apps-docs",
		"packages",
		"docs",
	}

	for _, dir := range dirs {
		fullPath := filepath.Join(qkb.targetDir, dir)
		if err := os.MkdirAll(fullPath, 0755); err != nil {
			return fmt.Errorf("create dir %s: %w", fullPath, err)
		}
	}

	log.Println("✅ Directories created")
	return nil
}

// copyImportantFiles copies important files
func (qkb *QuickKnowledgeBuilder) copyImportantFiles() error {
	log.Println("📁 Copying important files...")

	// Important files to copy
	importantFiles := []struct {
		source string
		target string
	}{
		{"AGENTS.md", "docs/AGENTS.md"},
		{"README.md", "docs/README.md"},
		{"apps-docs/00-index/INDEX.md", "apps-docs/INDEX.md"},
		{"apps-docs/03-operations/INDEX.md", "apps-docs/OPERATIONS.md"},
		{"apps-docs/01-architecture/INDEX.md", "apps-docs/ARCHITECTURE.md"},
		{"Ti-learning-lab/README.md", "content/skills/TI_LEARNING_LAB.md"},
		{"Ti-learning-lab/WORKFLOW.md", "content/workflows/TI_WORKFLOW.md"},
		{"Ti-learning-lab/MANIFEST.md", "content/rules/TI_MANIFEST.md"},
		{"apps/ticrew/README.md", "content/agents/TICREW.md"},
		{"apps/router/README.md", "content/agents/ROUTER.md"},
	}

	copied := 0
	for _, file := range importantFiles {
		sourcePath := filepath.Join(qkb.sourceDir, file.source)
		targetPath := filepath.Join(qkb.targetDir, file.target)

		if _, err := os.Stat(sourcePath); err == nil {
			if err := qkb.copyFile(sourcePath, targetPath); err == nil {
				copied++
				log.Printf("✅ Copied: %s", file.source)
			} else {
				log.Printf("❌ Failed to copy: %s", file.source)
			}
		} else {
			log.Printf("⚠️  Not found: %s", file.source)
		}
	}

	log.Printf("✅ Copied %d important files", copied)
	return nil
}

// copyFile copies a file
func (qkb *QuickKnowledgeBuilder) copyFile(src, dst string) error {
	// Create target directory
	if err := os.MkdirAll(filepath.Dir(dst), 0755); err != nil {
		return err
	}

	// Read source
	content, err := os.ReadFile(src)
	if err != nil {
		return err
	}

	// Write target
	return os.WriteFile(dst, content, 0644)
}

