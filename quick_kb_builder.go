// countFiles counts files in knowledge base
func (qkb *QuickKnowledgeBuilder) countFiles() int {
	count := 0

	filepath.Walk(qkb.targetDir, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() {
			return nil
		}

		if strings.HasSuffix(strings.ToLower(path), ".md") {
			count++
		}
		return nil
	})

	return count
}

// printSummary prints build summary
func (qkb *QuickKnowledgeBuilder) printSummary() {
	log.Println("=== 📊 BUILD SUMMARY ===")
	log.Printf("Build Time: %s", time.Since(qkb.startTime))
	log.Printf("Target: %s", qkb.targetDir)
	log.Printf("Files: %d", qkb.countFiles())
	log.Println("🎉 Quick knowledge base completed!")
}
